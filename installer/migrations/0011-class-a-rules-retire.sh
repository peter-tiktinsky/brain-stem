#!/bin/bash
# migration: 0011-class-a-rules-retire
# min_from: v0.0.0
# applies_at: v1.19.0
#
# Retire the four former always-on rule seeds from an EXISTING adopter home. install.sh
# seeds NO rules/ entries any more — the seeder that wrote these four preserved on exist,
# so a seed that install.sh stops writing is never removed by an upgrade on its own, and
# a migration is the only delivery path for the retirement. min_from is v0.0.0 because a
# home seeded at ANY prior release may carry the entries; applies_at is v1.19.0, the
# release that stops seeding them.
#
# ONE arm per entry, over a roster that is HARDCODED here because a migration is a frozen
# record of what it retired (the table's retired roster is the cross-check, not the source):
#   rules/00-project-binder-pointer.md      -> the situating card is injected at SessionStart
#                                              by hooks/session-start-project-context.sh
#   rules/10-pre-research-library-check.md  -> hooks/pre-research-check.sh (a required
#                                              UserPromptSubmit hook) injects library coverage
#                                              on research intent
#   rules/20-work-project-register.md       -> hooks/pre-write-guard.sh advises on the first
#                                              write under an unregistered ~/work/<spoke>/
#   rules/30-durable-artifact-routing.md    -> hooks/pre-write-guard.sh names the
#                                              capture/graduate commands when it denies a
#                                              plans-root write and flags a non-universal
#                                              _library/ article
# Each arm is complete-or-no-op and touches ONLY $CLAUDE_HOME/rules/<entry>:
#   absent                                   -> no-op
#   sha in the entry's historical set        -> rm -f + a stderr line naming the carrier
#   anything else (adopter-edited bytes)     -> LEFT IN PLACE, with an ACTION advisory
#   rm failure                               -> advisory, left in place
#
# The ACTION advisory is the one line an adopter has to act on, so it carries the stable
# prefix `0011: ACTION ` on its own stderr line: install.sh re-prints every
# `^[0-9]{4}: ACTION ` line as the first bullet after `next-steps:` and records them under
# `migrations_action_required:` in the provenance log. The removed-cleanly and rm-failed
# lines keep the plain `0011: ` prefix — they need no action.
#
# Recognition is by the sha256 table class-a-rules-sha-table.sh, sourced from this
# migration's own directory and GENERATED by tools/generate-class-a-sha-table.sh from the
# project's git history: every body ever seeded, each in both the bytes the seeder wrote
# (no trailing newline) and the same bytes with one, because an editor that opens and saves
# a rule file adds the newline back and the adopter has changed nothing. An absent or
# unreadable table, or a home with no sha tool, degrades to a full no-op: the migration
# never guesses, and NOTHING an adopter wrote is ever destroyed.
#
# Idempotent: a second run finds every entry absent or already adjudicated as adopter
# bytes — no writes, rc 0. A fresh install is a full no-op (no rules/ directory exists).
#
# Advisories go to stderr; stdout stays clean for the runner. python3 is NOT required.
# bash-3.2 clean; set -u. Exit 0 always.
set -u

CLAUDE_HOME_RES="${CLAUDE_HOME:-$HOME/.claude}"
case "$CLAUDE_HOME_RES" in */) CLAUDE_HOME_RES="${CLAUDE_HOME_RES%/}" ;; esac
RULES_DIR="$CLAUDE_HOME_RES/rules"

# --- recognition table (sourced from this migration's own directory) ---------
MIG_SELF_DIR="$(cd "$(dirname "$0")" 2>/dev/null && pwd)" || MIG_SELF_DIR=""
TABLE="$MIG_SELF_DIR/class-a-rules-sha-table.sh"
if [ -z "$MIG_SELF_DIR" ] || [ ! -f "$TABLE" ]; then
  printf '0011: recognition table not found beside this migration — cannot tell shipped bytes from adopter bytes; no-op (nothing changed)\n' >&2
  exit 0
fi
# shellcheck disable=SC1090
. "$TABLE" || {
  printf '0011: recognition table unreadable — no-op (nothing changed)\n' >&2
  exit 0
}

# --- sha helper (pure shell; degrades to "" so an unrecognisable file is kept) -
file_sha() {  # $1 = abs path -> sha256 hex, or "" if no sha tool / unreadable
  if command -v shasum >/dev/null 2>&1; then
    shasum -a 256 "$1" 2>/dev/null | awk '{print $1}'
  elif command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" 2>/dev/null | awk '{print $1}'
  else
    printf ''
  fi
}

# --- oldest/empty precondition: absent rules dir -> no-op --------------------
if [ ! -d "$RULES_DIR" ]; then
  printf '0011: rules dir absent (%s) — no-op (nothing to retire)\n' "$RULES_DIR" >&2
  exit 0
fi

# --- one arm per retired entry ------------------------------------------------
# retire_entry <basename> <carrier hook> <moment>
#   <carrier hook> = the shipped hook that delivers the same guidance now
#   <moment>       = when that hook fires (the sentence the advisory prints)
# The advisory ends with the command that prints the rule beside what its carrier delivers
# (rules-hygiene.sh --compare-retired); the path is shell-quoted, so a home path that holds a
# space or a quote runs as printed.
check_script="$(printf '%q' "$CLAUDE_HOME_RES/skills/librarian/capabilities/rules-hygiene.sh")"
retire_entry() {
  fname="$1"; carrier="$2"; moment="$3"
  target="$RULES_DIR/$fname"
  [ -f "$target" ] || return 0                     # absent -> no-op
  dsha="$(file_sha "$target")"
  if [ -n "$dsha" ] && class_a_historical_shas "$fname" | grep -qxF "$dsha"; then
    if rm -f "$target" 2>/dev/null; then
      printf '0011: removed rules/%s (bytes match a shipped seed). The same guidance is delivered by %s %s.\n' "$fname" "$carrier" "$moment" >&2
    else
      printf '0011: rm failed for rules/%s — left in place\n' "$fname" >&2
    fi
  else
    printf '0011: ACTION rules/%s is no longer shipped; its guidance is delivered by %s %s; keep it only for what your edit adds beyond that, otherwise delete it. Check: run %s --compare-retired %s to print the rule beside what %s delivers.\n' \
      "$fname" "$carrier" "$moment" "$check_script" "$fname" "$carrier" >&2
  fi
  return 0
}

retire_entry "00-project-binder-pointer.md" \
  "hooks/session-start-project-context.sh" \
  "at SessionStart, where the situating card is injected"
retire_entry "10-pre-research-library-check.md" \
  "hooks/pre-research-check.sh" \
  "on research intent (a required UserPromptSubmit hook that injects library coverage)"
retire_entry "20-work-project-register.md" \
  "hooks/pre-write-guard.sh" \
  "on the first write under an unregistered ~/work/<spoke>/"
retire_entry "30-durable-artifact-routing.md" \
  "hooks/pre-write-guard.sh" \
  "when it denies a plans-root write (naming the capture/graduate commands) and when it flags a non-universal _library/ article"

exit 0
