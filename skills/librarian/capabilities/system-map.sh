#!/bin/bash
# system-map — renders a map of what the installed system runs, one short page per member.
#
# A system built on brain-stem grows hooks, librarian capabilities, skills and scheduled jobs, and
# nothing shows them together. This command reads the installed home ($CLAUDE_HOME) and writes one
# six-line Markdown page per member plus an index, so "what does my system run?" is a folder you can
# open, and a capability, skill or hook of your own appears on the next render.
#
# Members, read from $CLAUDE_HOME and sorted by code point (LC_ALL=C):
#   hook         each distinct (event, matcher or empty, command) of settings.json .hooks; the
#                statusLine key is a top-level settings key, not under .hooks, and is not a member
#   capability   each key of .capabilities in every skills/*/capability-registry.json: the shipped
#                librarian's and every capability root of your own
#   skill        each skills/<name>/ folder that holds a SKILL.md
#   job          each job stem of templates/launchd/<job>.plist.tmpl and of the rendered
#                Library/LaunchAgents.staging/<label prefix>.<job>.plist (the stem is the text after
#                the last dot of the plist name without .plist); a template and its plist are one job
#
# Pages, under the output root:
#   hook/<event>--<matcher slug>--<command stem>.md   matcher slug: lowercased, each run of characters
#                outside a-z and 0-9 becomes one dash, outer dashes trimmed, "any" when empty; command
#                stem: the basename of the command's first word without .sh
#   capability/<skill>--<capability>.md   skill/<name>.md   job/<stem>.md
#   index.md     a title line, then one line "- <kind>: <count>" per kind (not a page)
# Two members whose page names collide (only your own hooks can) take --2, --3 on the later stems in
# member order, so the page count always equals the member count. Each page holds, in this order and
# with no date, host or user name: "# <kind>: <page stem>"; Trigger (hook: "<event> on <matcher or
# any>"; capability: its cron_block or none; skill: /<name>; job: launchd); Reads/Writes (a
# capability's output_contract.writes joined by "; ", else "see Source"); Lane (a capability's
# "<tier>; <invocation_modes joined by ', '>", else the kind); Script (relative to $CLAUDE_HOME); Source.
#
# The output root is --out DIR, else $SYSTEM_MAP_OUT, else $CLAUDE_STATE_ROOT/system-map. A root that
# holds the marker file .system-map-root (the single line "generated by system-map; never edit") is
# ours to rewrite; a non-empty root without it is refused and never touched.
#
# Output Contract:
#   Files written: --render only: the pages, index.md and .system-map-root under the output root,
#     each by temp file and rename; pages of members that no longer exist are removed from the four
#     kind folders of a marked root. Nothing outside those folders, index.md and the marker is
#     touched. --check and --dry-run write nothing.
#   stdout:
#     --render   `system-map: rendered pages=<n>`
#     --check    `system-map: ok pages=<n> members=<n>`, or exit 1 and
#                `system-map: drift: <detail> pages=<n> members=<m>`: <detail> is the root-relative
#                path of the first page, in code point order, whose bytes differ or that exists on
#                one side only, else `count` when every page matches and only index.md differs;
#                pages is the count of pages in the output root, members the count in the home
#     --dry-run  `system-map: pages=<n> members=<n>`
#   Refusals exit 2 with one stderr line, the tree unchanged:
#     `system-map: refused: <dir> is not empty and holds no .system-map-root`
#     `system-map: refused: <dir> is not a directory`
#     `system-map: refused: no output root (give --out, or set SYSTEM_MAP_OUT or CLAUDE_STATE_ROOT)`
#     `system-map: --out needs a value`
#     `system-map: one mode only (--render, --check or --dry-run)`
#     `system-map: unknown flag '<f>'`
#   A settings.json or registry that is not valid JSON, or a failed write, exits 1 with
#   `system-map: cannot read <path> as JSON` or `system-map: could not write <path>`.
#   Failure mode: block-and-log (nothing is rendered from a source that cannot be read).
#
# CLI:
#   system-map.sh [--render | --check | --dry-run] [--out DIR]     (default --check)
#   system-map.sh --help
#
# Bash 3.2 clean. Data reaches Python through argv, never a piped stdin.

set -uo pipefail
export LC_ALL=C

MODE=""
OUT_ARG=""

set_mode() {
  if [ -n "$MODE" ]; then echo "system-map: one mode only (--render, --check or --dry-run)" >&2; exit 2; fi
  MODE="$1"
}

while [ $# -gt 0 ]; do
  case "$1" in
    -h|--help) awk 'NR==1{next} /^#/{sub(/^# ?/,"");print;next} {exit}' "$0"; exit 0 ;;
    --render)  set_mode render; shift ;;
    --check)   set_mode check; shift ;;
    --dry-run) set_mode dry-run; shift ;;
    --out)
      if [ $# -lt 2 ] || [ -z "$2" ]; then echo "system-map: --out needs a value" >&2; exit 2; fi
      OUT_ARG="$2"; shift 2 ;;
    *) echo "system-map: unknown flag '$1'" >&2; exit 2 ;;
  esac
done
[ -n "$MODE" ] || MODE="check"

CLAUDE_HOME_RES="${CLAUDE_HOME:-$HOME/.claude}"
_REPO_LIB="$(cd "$(dirname "$0")/../../.." 2>/dev/null && pwd)/hooks/lib"
if [ -r "$CLAUDE_HOME_RES/hooks/lib/paths.sh" ]; then
  # shellcheck source=/dev/null
  source "$CLAUDE_HOME_RES/hooks/lib/paths.sh"
elif [ -r "$_REPO_LIB/paths.sh" ]; then
  # shellcheck source=/dev/null
  source "$_REPO_LIB/paths.sh"
fi

if [ -n "$OUT_ARG" ]; then
  OUT_DIR="$OUT_ARG"
elif [ -n "${SYSTEM_MAP_OUT:-}" ]; then
  OUT_DIR="$SYSTEM_MAP_OUT"
elif [ -n "${CLAUDE_STATE_ROOT:-}" ]; then
  OUT_DIR="$CLAUDE_STATE_ROOT/system-map"
else
  echo "system-map: refused: no output root (give --out, or set SYSTEM_MAP_OUT or CLAUDE_STATE_ROOT)" >&2
  exit 2
fi

python3 -I - "$MODE" "$CLAUDE_HOME_RES" "$OUT_DIR" <<'PY'
import json
import os
import re
import shutil
import sys
import tempfile

mode, home, out = sys.argv[1], sys.argv[2], sys.argv[3]
KINDS = ("hook", "capability", "skill", "job")
MARKER = ".system-map-root"
MARKER_LINE = "generated by system-map; never edit"


def die(message, code=1):
    sys.stderr.write("system-map: %s\n" % message)
    sys.exit(code)


def load_json(path):
    try:
        with open(path, encoding="utf-8") as fh:
            return json.load(fh)
    except (OSError, ValueError):
        die("cannot read %s as JSON" % path)


def one_line(text):
    return re.sub(r"[\r\n]+", " ", str(text))


def safe(text):
    return re.sub(r"[^A-Za-z0-9._-]", "-", text)


def unique(bases):
    used = set()
    names = []
    for base in bases:
        name = base
        n = 1
        while name in used:
            n += 1
            name = "%s--%d" % (base, n)
        used.add(name)
        names.append(name)
    return names


def page(kind, stem, trigger, writes, lane, script, source):
    lines = ["# %s: %s" % (kind, stem), "Trigger: %s" % trigger, "Reads/Writes: %s" % writes,
             "Lane: %s" % lane, "Script: %s" % script, "Source: %s" % source]
    return "".join(one_line(ln) + "\n" for ln in lines)


def listing(path):
    try:
        return sorted(os.listdir(path)) if os.path.isdir(path) else []
    except OSError:
        die("cannot list %s" % path)


# ---- the guard of a render: decided before anything is read or written --------------------------
if mode == "render" and os.path.lexists(out):
    if not os.path.isdir(out):
        die("refused: %s is not a directory" % out, 2)
    held = listing(out)
    marker = os.path.join(out, MARKER)
    marked = False
    if os.path.isfile(marker):
        with open(marker, encoding="utf-8", errors="replace") as fh:
            marked = MARKER_LINE in fh.read().split("\n")
    if held and not marked:
        die("refused: %s is not empty and holds no %s" % (out, MARKER), 2)

# ---- members ------------------------------------------------------------------------------------
hooks = set()
settings = os.path.join(home, "settings.json")
if os.path.isfile(settings):
    block = load_json(settings)
    block = block.get("hooks") if isinstance(block, dict) else None
    if isinstance(block, dict):
        for event, groups in block.items():
            if not isinstance(groups, list):
                continue
            for group in groups:
                if not isinstance(group, dict):
                    continue
                matcher = group.get("matcher")
                matcher = matcher if isinstance(matcher, str) else ""
                for entry in group.get("hooks") or []:
                    command = entry.get("command") if isinstance(entry, dict) else None
                    if isinstance(command, str) and command.strip():
                        hooks.add((event, matcher, command))

skills_dir = os.path.join(home, "skills")
skills = [n for n in listing(skills_dir) if os.path.isfile(os.path.join(skills_dir, n, "SKILL.md"))]
caps = []
for name in listing(skills_dir):
    registry = os.path.join(skills_dir, name, "capability-registry.json")
    if not os.path.isfile(registry):
        continue
    table = load_json(registry)
    table = table.get("capabilities") if isinstance(table, dict) else None
    if isinstance(table, dict):
        for key in table:
            row = table[key] if isinstance(table[key], dict) else {}
            caps.append((name, key, row))
caps.sort(key=lambda m: (m[0], m[1]))

jobs = {}
template_dir = os.path.join(home, "templates", "launchd")
for fn in listing(template_dir):
    if fn.endswith(".plist.tmpl") and os.path.isfile(os.path.join(template_dir, fn)):
        jobs.setdefault(fn[: -len(".plist.tmpl")], {"template": None, "plists": []})["template"] = \
            "templates/launchd/" + fn
staging_dir = os.path.join(home, "Library", "LaunchAgents.staging")
for fn in listing(staging_dir):
    if fn.endswith(".plist") and os.path.isfile(os.path.join(staging_dir, fn)):
        stem = fn[: -len(".plist")].rsplit(".", 1)[-1]
        jobs.setdefault(stem, {"template": None, "plists": []})["plists"].append(
            "Library/LaunchAgents.staging/" + fn)

# ---- pages --------------------------------------------------------------------------------------
pages = {}
counts = {}

hook_members = sorted(hooks)
stems = []
for event, matcher, command in hook_members:
    slug = re.sub(r"[^a-z0-9]+", "-", matcher.lower()).strip("-") or "any"
    word = command.split()[0].rsplit("/", 1)[-1]
    if word.endswith(".sh"):
        word = word[: -len(".sh")]
    stems.append("%s--%s--%s" % (safe(event), slug, safe(word) or "none"))
for (event, matcher, command), stem in zip(hook_members, unique(stems)):
    script = command.split()[0]
    if script.startswith("~/.claude/"):
        script = script[len("~/.claude/"):]
    pages["hook/%s.md" % stem] = page("hook", stem, "%s on %s" % (event, matcher or "any"),
                                      "see Source", "hook", script, "settings.json")
counts["hook"] = len(hook_members)

stems = unique([safe(skill) + "--" + safe(key) for skill, key, _ in caps])
for (skill, key, row), stem in zip(caps, stems):
    contract = row.get("output_contract") if isinstance(row.get("output_contract"), dict) else {}
    writes = contract.get("writes")
    writes = "; ".join(str(w) for w in writes) if isinstance(writes, list) else ""
    modes = row.get("invocation_modes")
    modes = ", ".join(str(m) for m in modes) if isinstance(modes, list) else ""
    tier = row.get("tier") if isinstance(row.get("tier"), str) else ""
    lane = "; ".join(p for p in (tier, modes) if p) or "capability"
    cron = row.get("cron_block")
    script = row.get("script")
    pages["capability/%s.md" % stem] = page(
        "capability", stem, cron if cron not in (None, "") else "none", writes or "see Source", lane,
        "skills/%s/%s" % (skill, script) if isinstance(script, str) and script else "none",
        "skills/%s/capability-registry.json" % skill)
counts["capability"] = len(caps)

for skill, stem in zip(skills, unique([safe(s) for s in skills])):
    path = "skills/%s/SKILL.md" % skill
    pages["skill/%s.md" % stem] = page("skill", stem, "/" + skill, "see Source", "skill", path, path)
counts["skill"] = len(skills)

job_stems = sorted(jobs)
for stem, name in zip(job_stems, unique([safe(s) for s in job_stems])):
    parts = ([jobs[stem]["template"]] if jobs[stem]["template"] else []) + sorted(jobs[stem]["plists"])
    pages["job/%s.md" % name] = page("job", name, "launchd", "see Source", "job", parts[0], "; ".join(parts))
counts["job"] = len(job_stems)

members = sum(counts.values())
index = "# system map\n" + "".join("- %s: %d\n" % (k, counts[k]) for k in KINDS)

if mode == "dry-run":
    sys.stdout.write("system-map: pages=%d members=%d\n" % (len(pages), members))
    sys.exit(0)


# ---- writing and reading a tree -----------------------------------------------------------------
def put(path, text):
    data = text.encode("utf-8")
    tmp = "%s.tmp.%d" % (path, os.getpid())
    try:
        if os.path.isfile(path):
            with open(path, "rb") as fh:
                if fh.read() == data:
                    return
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(tmp, "wb") as fh:
            fh.write(data)
        os.replace(tmp, path)
    except OSError:
        try:
            os.remove(tmp)
        except OSError:
            pass
        die("could not write %s" % path)


def write_tree(root, with_marker):
    # the marker goes first, so a render that stops half way still leaves a root it may rewrite
    if with_marker:
        put(os.path.join(root, MARKER), MARKER_LINE + "\n")
    for rel in sorted(pages):
        put(os.path.join(root, rel), pages[rel])
    put(os.path.join(root, "index.md"), index)


def read_pages(root):
    found = {}
    for kind in KINDS:
        folder = os.path.join(root, kind)
        for fn in listing(folder):
            full = os.path.join(folder, fn)
            if fn.endswith(".md") and os.path.isfile(full):
                try:
                    with open(full, "rb") as fh:
                        found["%s/%s" % (kind, fn)] = fh.read()
                except OSError:
                    die("cannot read %s" % full)
    return found


if mode == "render":
    write_tree(out, True)
    for kind in KINDS:
        folder = os.path.join(out, kind)
        for fn in listing(folder):
            full = os.path.join(folder, fn)
            if fn.endswith(".md") and ("%s/%s" % (kind, fn)) not in pages and not os.path.isdir(full):
                try:
                    os.remove(full)
                except OSError:
                    die("could not remove %s" % full)
        if os.path.isdir(folder) and not listing(folder):
            try:
                os.rmdir(folder)
            except OSError:
                die("could not remove %s" % folder)
    sys.stdout.write("system-map: rendered pages=%d\n" % len(pages))
    sys.exit(0)

# mode == "check": render to a temp tree, compare it with the output root
scratch = tempfile.mkdtemp(prefix="system-map.")
try:
    write_tree(scratch, False)
    want = read_pages(scratch)
    have = read_pages(out)
    detail = ""
    for rel in sorted(set(want) | set(have)):
        if want.get(rel) != have.get(rel):
            detail = rel
            break
    if not detail:
        current = os.path.join(out, "index.md")
        stored = None
        if os.path.isfile(current):
            with open(current, "rb") as fh:
                stored = fh.read()
        if stored != index.encode("utf-8"):
            detail = "count"
finally:
    shutil.rmtree(scratch, ignore_errors=True)

if detail:
    sys.stdout.write("system-map: drift: %s pages=%d members=%d\n" % (detail, len(have), members))
    sys.exit(1)
sys.stdout.write("system-map: ok pages=%d members=%d\n" % (len(have), members))
sys.exit(0)
PY
